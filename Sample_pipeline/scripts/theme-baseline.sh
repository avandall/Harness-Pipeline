#!/usr/bin/env bash
# STEP 0 of every migration — the starting-point theme ("baseline").
#
# WHAT THIS ENCODES (a harness-engineering pattern): the agent never builds "from nothing". It starts from a
# known, committed base theme — its stock sections, snippets, assets, settings and locales are the
# vocabulary the migration reuses — and every fresh run starts from EXACTLY that baseline again, so two
# runs are comparable and a half-finished run can never leak into the next one. The original harness
# did this by hand ("Reset theme to pristine default … for a fresh plan run" commits); this script makes
# the step explicit, cheap, and safe. The harness (docs/prompts/scripts/migrations scaffold) is never
# touched by a reset — only theme/ and the per-page evidence packs.
#
# Usage:
#   scripts/theme-baseline.sh init     [--from-store | --clone-url <git-url>]
#        create theme/: clone Dawn (default), another theme repo, or PULL the store's $SHOPIFY_THEME_ID
#        (e.g. a merchant's existing theme you must build on). Then commit it as the baseline.
#   scripts/theme-baseline.sh snapshot  mark the current theme/ as THE baseline (git tag theme-baseline)
#   scripts/theme-baseline.sh catalog   print the stock section / template / asset / locale inventory (seeds migrations/_sections.md)
#   scripts/theme-baseline.sh push-target [<name>]
#        push theme/ to a NEW unpublished theme on the store and print its id (→ SHOPIFY_THEME_ID); never the live theme
#   scripts/theme-baseline.sh reset    restore theme/ to the baseline tag + clear per-page packs, .ralph state, queue
#        (keeps the harness + migrations/_brief.md + reference/); refuses with uncommitted tracked changes
#
# Tunables: BASELINE_TAG (default theme-baseline), THEME_DIR (default theme), SHOPIFY_STORE/SHOPIFY_THEME_ID from .env
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"; cd "$ROOT"
THEME_DIR="${THEME_DIR:-theme}"
TAG="${BASELINE_TAG:-theme-baseline}"
[ -f .env ] && { set -a; . ./.env; set +a; }
STORE="${SHOPIFY_STORE:-}"
log() { printf '[baseline] %s\n' "$*"; }
need_store() { [ -n "$STORE" ] || { log "ERROR: SHOPIFY_STORE not set (.env)"; exit 2; }; }

cmd="${1:-}"; shift || true
case "$cmd" in
  init)
    [ ! -e "$THEME_DIR" ] || { log "ERROR: $THEME_DIR already exists — remove it or use 'reset'"; exit 2; }
    if [ "${1:-}" = "--from-store" ]; then
      need_store; [ -n "${SHOPIFY_THEME_ID:-}" ] || { log "ERROR: SHOPIFY_THEME_ID not set"; exit 2; }
      log "pulling theme $SHOPIFY_THEME_ID from $STORE into $THEME_DIR/ (the merchant's starting point)"
      mkdir -p "$THEME_DIR"
      shopify theme pull --store "$STORE" --theme "$SHOPIFY_THEME_ID" --path "$THEME_DIR"
    else
      URL="https://github.com/Shopify/dawn.git"
      [ "${1:-}" != "--clone-url" ] || URL="$2"
      log "cloning $URL into $THEME_DIR/ (Shopify's default 'theme init' would give the Skeleton starter; we pin the URL)"
      shopify theme init "$THEME_DIR" --clone-url "$URL"
      rm -rf "$THEME_DIR/.git" "$THEME_DIR/.github"        # a theme inside the harness repo must not carry its own git
    fi
    log "theme ready. Review it, then: git add $THEME_DIR && git commit -m 'theme: baseline' && scripts/theme-baseline.sh snapshot"
    ;;
  snapshot)
    [ -z "$(git status --porcelain -- "$THEME_DIR")" ] || { log "ERROR: commit $THEME_DIR/ first — a baseline is a committed state"; exit 1; }
    git tag -f "$TAG" >/dev/null
    log "baseline = $(git rev-parse --short HEAD) tagged '$TAG' (theme fingerprint: $(node scripts/migration-state.mjs fingerprint 2>/dev/null || echo n/a))"
    log "share it: git push origin $TAG   (clones then get the same reset point)"
    ;;
  catalog)
    echo "# Base theme catalog — the vocabulary migrations reuse (generated by scripts/theme-baseline.sh catalog)"
    echo; echo "## Sections (theme/sections) — stock building blocks; reuse-first, author new ones only when no type fits"
    ls "$THEME_DIR/sections" | sed 's/\.liquid$//' | sed 's/^/- /'
    echo; echo "## Templates (theme/templates)"; ls "$THEME_DIR/templates" | sed 's/^/- /'
    echo; echo "## Snippets (theme/snippets)"; ls "$THEME_DIR/snippets" | sed 's/\.liquid$//' | tr '\n' ' '; echo
    echo; echo "## Assets (theme/assets): $(ls "$THEME_DIR/assets" | wc -l | tr -d ' ') files (css/js/icons/images) — migrated assets are ADDED here byte-for-byte"
    echo; echo "## Locales: $(ls "$THEME_DIR/locales" | wc -l | tr -d ' ') files · Settings: theme/config/settings_schema.json (+ settings_data.json presets: $(node -e 'const d=require("./'"$THEME_DIR"'/config/settings_data.json");console.log(Object.keys(d.presets||{}).join(", "))' 2>/dev/null))"
    ;;
  push-target)
    need_store
    NAME="${1:-harness-dev}"
    log "pushing $THEME_DIR/ to a NEW unpublished theme '$NAME' on $STORE (never the live theme)"
    OUT="$(shopify theme push --store "$STORE" --path "$THEME_DIR" --unpublished --theme "$NAME" --json 2>/dev/null | tail -1)"
    ID="$(printf '%s' "$OUT" | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{try{console.log(JSON.parse(s).theme.id)}catch{process.exit(1)}})')" || { log "ERROR: push did not return a theme id: $OUT"; exit 1; }
    log "created unpublished theme id=$ID → put it in .env as SHOPIFY_THEME_ID"
    printf '%s\n' "$ID"
    ;;
  reset)
    git rev-parse -q --verify "refs/tags/$TAG" >/dev/null || { log "ERROR: no '$TAG' tag — run 'snapshot' on a committed baseline first"; exit 2; }
    [ -z "$(git status --porcelain --untracked-files=no)" ] || { log "ERROR: commit/stash tracked changes first"; exit 1; }
    log "restoring $THEME_DIR/ to baseline $TAG ($(git rev-parse --short "$TAG"))"
    git rm -rq --ignore-unmatch -- "$THEME_DIR" >/dev/null 2>&1 || true
    git checkout -q "$TAG" -- "$THEME_DIR"
    log "clearing per-page evidence packs, queue, and loop state (harness, _brief.md, _example/, reference/ untouched)"
    for d in migrations/*/; do case "$d" in migrations/_*) ;; *) rm -rf "$d";; esac; done
    rm -f migrations/_queue.tsv migrations/_scope.json
    rm -rf .ralph
    "$0" catalog > migrations/_sections.md          # re-seed the reuse catalog from the pristine baseline
    git add -A -- "$THEME_DIR" migrations
    log "done — review 'git status', commit as 'reset: theme to baseline for a fresh run', then push the baseline to your unpublished target"
    ;;
  *)
    sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
